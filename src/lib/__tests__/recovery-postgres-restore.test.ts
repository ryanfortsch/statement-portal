/** Explicit opt-in: creates a temporary synthetic PostgreSQL cluster, never reads app env files. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { generateKeyPairSync, randomUUID } from 'node:crypto';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import tar from 'tar-stream';
import { createPostgresRecoverySource, createPostgresRolesSource } from '../recovery-postgres.ts';
import { createDatabaseArchiveSource } from '../recovery-database-archive.ts';
import { createStorageRecoverySource } from '../recovery-storage.ts';
import { createEncryptedRecoveryBundle, type RecoverySource } from '../recovery-export.ts';

const pg = process.env.RECOVERY_TEST_PG_BIN, age = process.env.RECOVERY_TEST_AGE, keygen = process.env.RECOVERY_TEST_AGE_KEYGEN;
test('real PostgreSQL -> age -> isolated restore preserves rows, sequences, FK, RLS, receipts and storage', {
  skip: !pg || !age || !keygen ? 'Set RECOVERY_TEST_PG_BIN, RECOVERY_TEST_AGE and RECOVERY_TEST_AGE_KEYGEN for isolated restore' : false,
  timeout: 60_000,
}, async t => {
  // Use a short private socket directory; PostgreSQL Unix socket paths are bounded.
  const directory = await mkdtemp(join(tmpdir(), 'helm-pg-'));
  const data = join(directory, 'cluster'); let started = false;
  const target = await mkdtemp(join(tmpdir(), 'helm-restore-'));
  const targetData = join(target, 'cluster'); let targetStarted = false;
  const env = { NODE_ENV: 'test' as const, PATH: '/usr/bin:/bin', LANG: 'C', PGHOST: directory, PGPORT: '5432', PGUSER: 'recovery_owner', PGPASSFILE: '/dev/null', PGSERVICEFILE: '/dev/null' };
  function run(binary: string, args: string[], input?: Buffer | string) {
    return execFileSync(join(pg!, binary), args, { env, input, maxBuffer: 8_000_000, timeout: 20_000, stdio: ['pipe', 'pipe', 'pipe'] });
  }
  function restoreRun(binary: string, args: string[], input?: Buffer | string) {
    return execFileSync(join(pg!, binary), args, { env: { ...env, PGHOST: target, PGUSER: 'restore_admin' }, input, maxBuffer: 8_000_000, timeout: 20_000, stdio: ['pipe', 'pipe', 'pipe'] });
  }
  t.after(async () => {
    if (started) run('pg_ctl', ['-D', data, '-m', 'immediate', '-w', 'stop']);
    if (targetStarted) restoreRun('pg_ctl', ['-D', targetData, '-m', 'immediate', '-w', 'stop']);
    await rm(directory, { recursive: true, force: true });
    await rm(target, { recursive: true, force: true });
  });
  run('initdb', ['-D', data, '--username=recovery_owner', '--auth-local=trust', '--auth-host=reject', '--no-locale', '--encoding=UTF8']);
  // TCP disabled. Only this user's 0700 temporary Unix-socket directory is reachable.
  run('pg_ctl', ['-D', data, '-l', join(directory, 'synthetic-postgres.log'), '-o', `-h '' -k '${directory}'`, '-w', 'start']);
  started = true;
  restoreRun('initdb', ['-D', targetData, '--username=restore_admin', '--auth-local=trust', '--auth-host=reject', '--no-locale', '--encoding=UTF8']);
  restoreRun('pg_ctl', ['-D', targetData, '-l', join(target, 'synthetic-postgres.log'), '-o', `-h '' -k '${target}'`, '-w', 'start']);
  targetStarted = true;
  run('createdb', ['source']); restoreRun('createdb', ['restored']);
  const sql = (db: string, text: string) => (db === 'restored' ? restoreRun : run)('psql', ['-X', '--no-password', '--set=ON_ERROR_STOP=1', '-At', '-d', db], text).toString().trim();
  sql('source', `
    CREATE ROLE recovery_guest;
    CREATE TABLE bookings (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status text NOT NULL, amount numeric(14,2) NOT NULL);
    INSERT INTO bookings(status, amount) SELECT CASE WHEN i % 2 = 0 THEN 'cancelled' ELSE 'confirmed' END, i * 1.25 FROM generate_series(1,5001) i;
    CREATE TABLE receipts (id bigint PRIMARY KEY, booking_id bigint REFERENCES bookings(id), status text, send_at time, hold boolean);
    INSERT INTO receipts VALUES (1, 1, 'sent', '15:00', false), (2, 2, 'cancelled', '15:00', true);
    ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
    CREATE POLICY only_confirmed ON bookings FOR SELECT TO recovery_guest USING (status = 'confirmed');
    GRANT USAGE ON SCHEMA public TO recovery_guest;
    GRANT SELECT ON bookings TO recovery_guest;
    CREATE FUNCTION booking_total() RETURNS numeric LANGUAGE SQL STABLE AS 'SELECT sum(amount) FROM bookings';
  `);
  const connection = { host: directory, expectedHost: directory, port: 5432, user: 'recovery_owner', password: 'synthetic-trust-fixture', database: 'source', tls: { mode: 'local-socket' as const } };
  const dump = createPostgresRecoverySource({ pgDumpExecutable: join(pg!, 'pg_dump'), timeoutMs: 20_000, connection });
  const database = createDatabaseArchiveSource({ database: dump, maxDatabaseBytes: 8_000_000, timeoutMs: 30_000,
    roles: () => createPostgresRolesSource({ pgDumpAllExecutable: join(pg!, 'pg_dumpall'), timeoutMs: 20_000, connection }) });
  const storage = createStorageRecoverySource({ maxObjects: 100, maxObjectBytes: 1000, maxTotalBytes: 1000, maxInventoryBytes: 10000, timeoutMs: 10000,
    stores: [{ id: 'synthetic', list: async () => ({ scope: 'synthetic-private-bucket', objects: [{ bucket: 'documents', key: 'signed.pdf', version: 'v1', bytes: 13, modifiedAt: '2026-01-01T00:00:00.000Z', access: 'private' }] }),
      read: async obj => ({ body: Readable.from(['synthetic-pdf']), version: obj.version, bytes: obj.bytes, modifiedAt: obj.modifiedAt, contentType: 'application/pdf' }) }] });
  const configuration: RecoverySource = { open: () => Readable.from([JSON.stringify({ synthetic: true, outboundJobsEnabled: false })]), assertComplete: async () => {} };
  const identity = join(directory, 'temporary-age-key');
  execFileSync(keygen!, ['-o', identity], { stdio: ['ignore', 'ignore', 'pipe'] });
  const recipient = execFileSync(keygen!, ['-y', identity], { encoding: 'utf8' }).trim();
  const keys = generateKeyPairSync('ed25519');
  const result = await createEncryptedRecoveryBundle({ parentDirectory: directory, ageExecutable: age!, recipient, timeoutMs: 30000, maxArtifactBytes: 8_000_000,
    signingPrivateKey: keys.privateKey.export({ type: 'pkcs8', format: 'pem' }).toString(), trustedSigningPublicKey: keys.publicKey.export({ type: 'spki', format: 'pem' }).toString(),
    sources: { database, storage, configuration }, metadata: { backupId: randomUUID(), scope: { projectRef: 'a'.repeat(20), environment: 'staging' },
      snapshotAt: new Date().toISOString(), expiresAt: new Date(Date.now() + 86400000).toISOString(), appCommit: 'b'.repeat(40) } }).catch(async () => {
        const runs = (await readdir(directory)).filter(name => /^[a-f0-9-]{36}$/.test(name));
        const artifacts = runs.length ? await readdir(join(directory, runs[0])) : [];
        throw new Error(`Synthetic recovery bundle failed after artifacts: ${artifacts.join(', ')}`);
      });
  assert.ok(dump.snapshotNotBefore());
  assert.deepEqual((await readdir(result.directory)).sort(), ['configuration.age', 'database.age', 'manifest.signed.json', 'storage.age']);
  const decrypted = (name: string) => execFileSync(age!, ['--decrypt', '-i', identity, join(result.directory, name)], { maxBuffer: 8_000_000 });
  const dbExtract = tar.extract(); dbExtract.end(decrypted('database.age')); const databaseFiles = new Map<string, Buffer>();
  for await (const entry of dbExtract) { const chunks: Buffer[] = []; for await (const chunk of entry) chunks.push(chunk); databaseFiles.set(entry.header.name, Buffer.concat(chunks)); }
  const dbManifest = JSON.parse(databaseFiles.get('database.json')!.toString());
  assert.equal(dbManifest.format, 'helm-postgres-tar-v1');
  assert.equal(sql('restored', "SELECT count(*) FROM pg_roles WHERE rolname IN ('recovery_owner', 'recovery_guest')"), '0');
  restoreRun('psql', ['-X', '--set=ON_ERROR_STOP=1', '-d', 'restored'], databaseFiles.get('roles.sql'));
  assert.equal(sql('restored', "SELECT count(*) FROM pg_roles WHERE rolname IN ('recovery_owner', 'recovery_guest')"), '2');
  assert.equal(sql('restored', "SELECT count(*) FROM pg_authid WHERE rolpassword IS NOT NULL"), '0');
  restoreRun('pg_restore', ['--exit-on-error', '--single-transaction', '-d', 'restored'], Buffer.concat(dbManifest.parts.map((p: {path: string}) => databaseFiles.get(p.path)!)));
  for (const query of ["SELECT count(*), sum(amount) FROM bookings", "SELECT * FROM receipts ORDER BY id", "SELECT booking_total()", "SET ROLE recovery_guest; SELECT count(*) FROM bookings", "SELECT nextval(pg_get_serial_sequence('bookings', 'id'))"]) {
    assert.equal(sql('restored', query), sql('source', query));
  }
  assert.equal(sql('restored', 'SELECT count(*) FROM bookings'), '5001');
  assert.equal(sql('restored', 'SET ROLE recovery_guest; SELECT count(*) FROM bookings'), 'SET\n2501');
  assert.throws(() => sql('restored', "INSERT INTO receipts VALUES (3, 99999999, 'pending', '15:00', false)"));
  const extract = tar.extract(); extract.end(decrypted('storage.age')); const files = new Map<string, Buffer>();
  for await (const entry of extract) { const parts: Buffer[] = []; for await (const chunk of entry) parts.push(chunk); files.set(entry.header.name, Buffer.concat(parts)); }
  const inventory = JSON.parse(files.get('inventory.json')!.toString());
  assert.equal(files.get(inventory.objects[0].archivePath)!.toString(), 'synthetic-pdf');
  assert.equal(JSON.parse(decrypted('configuration.age').toString()).outboundJobsEnabled, false);
  const corrupted = await readFile(join(result.directory, 'database.age')); corrupted[corrupted.length - 1] ^= 1;
  const corruptPath = join(directory, 'corrupted.age'); await writeFile(corruptPath, corrupted);
  assert.throws(() => execFileSync(age!, ['--decrypt', '-i', identity, corruptPath], { stdio: ['ignore', 'pipe', 'pipe'] }));
});
