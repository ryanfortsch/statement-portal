// Run with a locally installed @electric-sql/pglite module path; no hosted database IO.
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
if (!process.argv[2]) throw new Error('Pass the absolute PGlite module path');
const {PGlite} = await import(pathToFileURL(resolve(process.argv[2])).href);
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const root=new URL('../docs/guesty-exit/staging-storage/', import.meta.url);
const db=new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role;');
await db.exec(readFileSync(new URL('inventory-store.sql',root),'utf8'));
await db.exec(readFileSync(new URL('inventory-planning.sql',root),'utf8'));
const fresh=Date.now()+600000;
const state={snapshot:{version:1,coverage:[{complete:true,freshUntil:fresh}]},configurationVersion:1,connection:'synthetic',property:'home',generation:1,listing:'home'};
await db.query('insert into helm_pilot_inventory_snapshot values(1,1,1,$1)',[state]);
const journal={format:1,commands:[{kind:'enqueue',now:1000,intent:{id:'test',environment:'staging',connection:'synthetic',property:'home',generation:1,version:1,days:[{date:'2027-01-01',available:0,stopSell:true}]}}]};
const commit=async(s=1,c=1,j=0,p=journal,f=fresh)=>(await db.query('select helm_pilot_inventory_plan_commit($1,$2,$3,$4,$5) as ok',[s,c,j,p,f])).rows[0].ok;
assert.equal(await commit(2),false);assert.equal(await commit(1,2),false);assert.equal(await commit(1,1,0,journal,0),false);
assert.equal(await commit(1,1,0,journal,fresh+1),false);
await assert.rejects(()=>commit(1,1,0,{...journal,commands:[{...journal.commands[0],intent:{...journal.commands[0].intent,property:'other'}}]}),/identity mismatch/);
await db.exec('set role service_role');assert.equal(await commit(),true);assert.equal(await commit(),false);
const read=(await db.query('select helm_pilot_inventory_planning_read() as state')).rows[0].state;assert.equal(read.journalVersion,1);
await assert.rejects(()=>db.exec('delete from helm_pilot_inventory_snapshot'),/permission denied/);
await db.exec('reset role');
await assert.rejects(()=>db.exec('update helm_pilot_inventory_snapshot set state=state'),/versions must advance/);
await assert.rejects(()=>db.query("update helm_pilot_inventory_snapshot set snapshot_version=2,state=jsonb_set(jsonb_set(state,'{snapshot,version}','2'),'{connection}','\"other\"')"),/Configuration version/);
await db.exec('set role anon');await assert.rejects(()=>db.query('select helm_pilot_inventory_planning_read()'),/permission denied/);await db.exec('reset role');
const rls=(await db.query("select relrowsecurity from pg_class where relname='helm_pilot_inventory_snapshot'")).rows[0];assert.equal(rls.relrowsecurity,true);
console.log('PASS: SQL applied; consistent read, successful append, stale snapshot/config/journal, expired/extended freshness, wrong identity, version guards, RLS and role restrictions');
await db.close();
